#!/usr/bin/env node
'use strict';

// Отдельная публичная сборка UI Source: только стиль GUI, окно и ввод ключа.
// Секреты, Kernel и игровые модули сюда никогда не подмешиваются.
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const preview = args.includes('--preview');
function option(name, fallback) {
  const at = args.indexOf(name);
  if (at < 0) return fallback;
  if (!args[at + 1] || args[at + 1].startsWith('--')) throw new Error(`Missing value for ${name}`);
  return args[at + 1];
}
const keyUrl = option('--key-url', 'https://jnkie.com/get-key/violite-free');
if (keyUrl) {
  const url = new URL(keyUrl);
  if (url.protocol !== 'https:' || url.username || url.password || keyUrl.length > 512) {
    throw new Error('--key-url must be a public HTTPS URL without credentials (max 512 characters)');
  }
}
const output = path.resolve(option('--out', preview
  ? path.join(ROOT, 'dist', 'dev', 'Violite.loader.preview.lua')
  : path.join(ROOT, 'dist', 'release', 'Violite.loader.ui.lua')));
const read = file => fs.readFileSync(path.join(ROOT, file), 'utf8').replace(/^\uFEFF/, '');
const gui = read('Libraryes/GUI.lua');
const marker = '    --#loader-style-end';
if (gui.split(marker).length !== 2) throw new Error('Expected exactly one loader style boundary in GUI.lua');
const style = gui.slice(0, gui.indexOf(marker)) + '\n    return GUI\nend';
// JSON-экранирование строки здесь используется для Luau, не для shell-команд.
const luaString = value => JSON.stringify(value).replace(/\\u([0-9a-f]{4})/gi, (_, hex) => `\\u{${hex}}`);
const source = [
  '-- Violite UI Source — generated by build/key-loader.js.',
  `-- ${preview ? 'PREVIEW: no auth, no file writes, no SCRIPT_KEY changes.' : 'Paste the entire file into Jnkie UI Source. Original Code stays separate.'}`,
  'local createStyle = (function()', style, 'end)()',
  'local createPrompt = (function()', read('Libraryes/KeyLoaderUI.lua'), 'end)()',
  'local runLoader = (function()', read('KeyLoader.lua'), 'end)()',
  `local key = runLoader(createStyle, createPrompt, {Preview = ${preview}, KeyUrl = ${luaString(keyUrl)}})`,
  'if not key then return end',
  '-- UI Source finishes here; Jnkie continues with its protected loader.',
  '',
].join('\n');
for (const forbidden of ['JD_SECURE_REQUEST', 'proxySecret', 'responseSecret', 'KernelFactory', 'loadIconPack', 'VioDbg']) {
  if (source.includes(forbidden)) throw new Error(`Public loader contains forbidden content: ${forbidden}`);
}
fs.mkdirSync(path.dirname(output), {recursive:true});
fs.writeFileSync(output, source, 'utf8');
console.log(`Loader written: ${output} (${Math.ceil(Buffer.byteLength(source)/1024)} KB)`);
